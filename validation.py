import re
from datetime import date
from uuid import UUID

REPORT_TYPES = ("End of Year Internship", "Mini Senior Project")
STUDENT_FIELDS = {"first_name", "last_name", "double_major", "level", "reports"}
REPORT_FIELDS = {"student_id", "title", "type", "k1", "k2", "k3", "release_date"}
NAME_PATTERN = re.compile(r"[^\W\d_]+(?:[ '-][^\W\d_]+)*")
DATE_PATTERN = re.compile(r"\d{4}-\d{2}-\d{2}")
FINAL_LEVEL = 4
DOUBLE_MAJOR_MIN_LEVEL = 3


class ApiError(Exception):
    def __init__(self, status, code, message, details=None):
        super().__init__(message)
        self.status = status
        self.code = code
        self.message = message
        self.details = details

    def to_dict(self):
        error = {"status": self.status, "code": self.code, "message": self.message}
        if self.details:
            error["details"] = self.details
        return {"error": error}


def invalid(details):
    return ApiError(400, "VALIDATION_ERROR", "Request contains invalid fields", details)


def normalize_uuid(value):
    try:
        return str(UUID(value))
    except (TypeError, ValueError, AttributeError):
        return None


def parse_id(value, label="id"):
    uid = normalize_uuid(value)
    if uid is None:
        raise ApiError(400, "INVALID_ID", f"{label} must be a valid UUID")
    return uid


def check_report_count(level, double_major, count):
    limit = 2 if double_major else 1
    major = "double-major" if double_major else "single-major"
    noun = "reports" if limit > 1 else "report"
    if count > limit:
        raise ApiError(409, "RULE_VIOLATION", f"A {major} student can have at most {limit} {noun}")
    if level == FINAL_LEVEL and count != limit:
        raise ApiError(
            409,
            "RULE_VIOLATION",
            f"A final level {major} student must have exactly {limit} {noun} (would have {count})",
        )


def _unknown_fields(data, allowed, errors):
    for field in data.keys() - allowed:
        errors[field] = "is generated by the server" if field == "id" else "unknown field"


def _text(data, field, errors, max_len, required=True):
    value = data.get(field)
    if value is None:
        if required:
            errors[field] = "is required"
        return None
    if not isinstance(value, str):
        errors[field] = "must be a string"
        return None
    value = value.strip()
    if not value:
        errors[field] = "must not be empty"
    elif len(value) > max_len:
        errors[field] = f"must be at most {max_len} characters"
    return value


def _check_report(data, inline):
    errors = {}
    _unknown_fields(data, REPORT_FIELDS - {"student_id"} if inline else REPORT_FIELDS, errors)
    report = {}

    if not inline:
        if data.get("student_id") is None:
            errors["student_id"] = "is required"
        else:
            report["student_id"] = normalize_uuid(data["student_id"])
            if report["student_id"] is None:
                errors["student_id"] = "must be a valid UUID"

    report["title"] = _text(data, "title", errors, 200)

    report_type = _text(data, "type", errors, 50)
    if "type" not in errors:
        report_type = next((t for t in REPORT_TYPES if t.casefold() == report_type.casefold()), None)
        if report_type is None:
            errors["type"] = f"must be one of: {', '.join(REPORT_TYPES)}"
    report["type"] = report_type

    report["k1"] = _text(data, "k1", errors, 30)
    report["k2"] = _text(data, "k2", errors, 30, required=False)
    report["k3"] = _text(data, "k3", errors, 30, required=False)
    if report["k3"] and report["k2"] is None:
        errors["k3"] = "cannot be set without k2"
    seen = set()
    for field in ("k1", "k2", "k3"):
        if report[field] and field not in errors:
            if report[field].casefold() in seen:
                errors[field] = "duplicates another keyword"
            seen.add(report[field].casefold())

    raw_date = data.get("release_date")
    if raw_date is None:
        errors["release_date"] = "is required"
    elif not isinstance(raw_date, str) or not DATE_PATTERN.fullmatch(raw_date):
        errors["release_date"] = "must be a date in YYYY-MM-DD format"
    else:
        try:
            released = date.fromisoformat(raw_date)
        except ValueError:
            errors["release_date"] = "is not a valid calendar date"
        else:
            if released > date.today():
                errors["release_date"] = "cannot be in the future"
    report["release_date"] = raw_date

    return report, errors


def validate_login(data):
    errors = {}
    _unknown_fields(data, {"username", "password"}, errors)
    credentials = {}
    for field in ("username", "password"):
        value = data.get(field)
        if value is None:
            errors[field] = "is required"
        elif not isinstance(value, str) or not value:
            errors[field] = "must be a non-empty string"
        credentials[field] = value
    if errors:
        raise invalid(errors)
    return credentials


def validate_report(data):
    report, errors = _check_report(data, inline=False)
    if errors:
        raise invalid(errors)
    return report


def validate_student(data):
    """Returns the cleaned student and the list of inline reports to create with it."""
    errors = {}
    _unknown_fields(data, STUDENT_FIELDS, errors)
    student = {}

    for field in ("first_name", "last_name"):
        value = _text(data, field, errors, 50)
        if field not in errors and not NAME_PATTERN.fullmatch(value):
            errors[field] = "may only contain letters, single spaces, hyphens and apostrophes"
        student[field] = value

    double_major = data.get("double_major")
    if isinstance(double_major, bool):
        double_major = int(double_major)
    if double_major is None:
        errors["double_major"] = "is required"
    elif type(double_major) is not int or double_major not in (0, 1):
        errors["double_major"] = "must be true/false or 0/1"
    student["double_major"] = double_major

    level = data.get("level")
    if level is None:
        errors["level"] = "is required"
    elif type(level) is not int or not 1 <= level <= FINAL_LEVEL:
        errors["level"] = f"must be an integer between 1 and {FINAL_LEVEL}"
    student["level"] = level

    if double_major == 1 and "level" not in errors and level < DOUBLE_MAJOR_MIN_LEVEL:
        errors["double_major"] = f"is only allowed from level {DOUBLE_MAJOR_MIN_LEVEL}"

    reports = data.get("reports", [])
    if not isinstance(reports, list):
        errors["reports"] = "must be a list"
        reports = []
    cleaned_reports = []
    for i, item in enumerate(reports):
        if not isinstance(item, dict):
            errors[f"reports[{i}]"] = "must be an object"
            continue
        report, report_errors = _check_report(item, inline=True)
        errors.update({f"reports[{i}].{field}": msg for field, msg in report_errors.items()})
        cleaned_reports.append(report)

    if errors:
        raise invalid(errors)
    return student, cleaned_reports
